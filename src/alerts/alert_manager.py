"""
Intelligent Alert Management System for LandslideGuard.

Implements:
- Configurable experimental alert generation (Low, Moderate, High, Very High)
- Rich alert records (location, coordinates, probability, environmental context,
  model version, data source, status, timestamps)
- Full lifecycle management: new -> acknowledged -> resolved + audit history
- Duplicate suppression with configurable cooldown windows
- Automatic bypass on significant severity escalation (e.g., High -> Very High)
- Disabled-by-default external notification hooks (Email / SMS)

IMPORTANT: Alerts generated by this system are EXPERIMENTAL.
They must not be communicated as official disaster warnings.
"""

from __future__ import annotations

import math
from datetime import datetime, timezone
from typing import Any

import pandas as pd

from src.alerts.notifications import NotificationDispatcher
from src.database.models import (
    acknowledge_alert as db_acknowledge,
    create_alert,
    get_active_cooldown_alerts,
    get_alert_audit_log,
    get_alert_by_id,
    get_alerts,
    resolve_alert as db_resolve,
    save_prediction,
)
from src.risk.thresholds import get_thresholds
from src.utils.logging_config import get_logger
from src.utils.settings import get_setting

logger = get_logger(__name__)

ALERT_TRIGGER_CATEGORY = get_setting("alerts", "trigger_category") or "High"
COOLDOWN_MINUTES = int(get_setting("alerts", "cooldown_minutes") or 120)
MAX_ACTIVE_ALERTS = int(get_setting("alerts", "max_active_alerts") or 50)

SEVERITY_RANK: dict[str, int] = {
    "Low": 1,
    "Moderate": 2,
    "High": 3,
    "Very High": 4,
}

EXPERIMENTAL_NOTICE = (
    "⚠️ EXPERIMENTAL ALERT — This is a research prototype alert. "
    "It has NOT been validated and must NOT be used for evacuation "
    "or emergency management decisions."
)


class AlertManager:
    """Manages the complete lifecycle of experimental risk alerts."""

    def __init__(self, dispatcher: NotificationDispatcher | None = None) -> None:
        self._thresholds = get_thresholds()
        self.dispatcher = dispatcher or NotificationDispatcher()

    @staticmethod
    def evaluate_cooldown_policy(
        location_id: int | None,
        new_category: str,
        active_cooldown_alerts: list[dict[str, Any]] | None = None,
        now: datetime | None = None,
    ) -> dict[str, Any]:
        """Evaluate duplicate cooldown suppression vs. severity escalation.

        - If no un-resolved alert for the location is within its cooldown window:
          allow alert generation (`suppressed=False`).
        - If an active alert IS within cooldown and the new severity rank is strictly
          higher than all active cooldown alerts at that location:
          allow escalation alert (`suppressed=False`, `is_escalation=True`).
        - Otherwise suppress duplicate alert (`suppressed=True`).
        """
        if location_id is None and active_cooldown_alerts is None:
            return {
                "suppressed": False,
                "is_escalation": False,
                "escalated_from": None,
                "reason": "no_location_id",
            }

        active = (
            active_cooldown_alerts
            if active_cooldown_alerts is not None
            else get_active_cooldown_alerts(location_id, now=now)
        )
        if not active:
            return {
                "suppressed": False,
                "is_escalation": False,
                "escalated_from": None,
                "reason": "no_active_cooldown",
            }

        new_rank = SEVERITY_RANK.get(new_category, 0)
        highest_existing = max(
            active,
            key=lambda row: SEVERITY_RANK.get(str(row.get("risk_category", "")), 0),
        )
        prev_cat = str(highest_existing.get("risk_category", ""))
        prev_rank = SEVERITY_RANK.get(prev_cat, 0)

        if new_rank > prev_rank and prev_rank > 0:
            return {
                "suppressed": False,
                "is_escalation": True,
                "escalated_from": prev_cat,
                "reason": f"Severity escalation allowed ({prev_cat} -> {new_category}).",
            }

        return {
            "suppressed": True,
            "is_escalation": False,
            "escalated_from": None,
            "reason": f"Suppressed during cooldown ({prev_cat} active until {highest_existing.get('cooldown_ends_at')}).",
        }

    def evaluate_and_alert(
        self,
        risk_result: dict,
        location_id: int | None = None,
        location_name: str | None = None,
        latitude: float | None = None,
        longitude: float | None = None,
        supporting_env_info: dict | None = None,
        model_version: str | None = None,
        data_source: str | None = None,
        trigger_category: str | None = None,
        cooldown_minutes: int | None = None,
        now: datetime | None = None,
    ) -> dict | None:
        """Evaluate a risk estimate and generate a persisted experimental alert if warranted."""
        if not isinstance(risk_result, dict):
            logger.debug("Invalid risk_result; skipping alert evaluation.")
            return None

        probability = risk_result.get("probability")
        if probability is None:
            logger.debug("Missing risk probability; skipping alert evaluation safely.")
            return None
        try:
            prob_f = float(probability)
        except (TypeError, ValueError):
            logger.debug("Non-numeric risk probability %r; skipping alert evaluation.", probability)
            return None
        if not math.isfinite(prob_f):
            logger.debug("Non-finite risk probability %r; skipping alert evaluation.", probability)
            return None

        risk_category = risk_result.get("risk_category")
        if not risk_category or risk_category == "Unknown":
            risk_category = self._thresholds.classify(prob_f).value

        active_trigger = trigger_category or ALERT_TRIGGER_CATEGORY
        if not self._thresholds.exceeds_alert_threshold(prob_f, active_trigger):
            logger.debug(
                "Risk category '%s' (prob=%.4f) below trigger threshold '%s'. No alert.",
                risk_category,
                prob_f,
                active_trigger,
            )
            return None

        eval_now = now or datetime.now(timezone.utc)
        if eval_now.tzinfo is None:
            eval_now = eval_now.replace(tzinfo=timezone.utc)

        cooldown_check = self.evaluate_cooldown_policy(
            location_id=location_id,
            new_category=risk_category,
            now=eval_now,
        )
        if cooldown_check["suppressed"]:
            logger.info(
                "Alert suppressed for location %s (%s): %s",
                location_name or location_id,
                risk_category,
                cooldown_check["reason"],
            )
            return None

        features_used = risk_result.get("features_used") or {}
        resolved_lat = latitude if latitude is not None else features_used.get("latitude")
        resolved_lon = longitude if longitude is not None else features_used.get("longitude")
        resolved_env = supporting_env_info if supporting_env_info is not None else features_used
        resolved_model = (
            model_version
            or risk_result.get("model_version")
            or risk_result.get("model_name")
            or risk_result.get("method")
            or "unknown"
        )
        resolved_source = (
            data_source
            or risk_result.get("data_source")
            or risk_result.get("source_label")
            or f"RiskEngine ({risk_result.get('method', 'unknown')})"
        )

        # Save linked prediction record
        prediction_id = save_prediction(
            probability=prob_f,
            risk_category=risk_category,
            model_name=str(resolved_model),
            method=risk_result.get("method", "unknown"),
            input_features=features_used,
            warnings=risk_result.get("warnings", []),
            location_id=location_id,
            is_experimental=True,
        )

        eff_cooldown = int(cooldown_minutes if cooldown_minutes is not None else COOLDOWN_MINUTES)
        alert_id = create_alert(
            risk_category=risk_category,
            probability=prob_f,
            location_id=location_id,
            prediction_id=prediction_id,
            cooldown_minutes=eff_cooldown,
            location_name=location_name,
            latitude=resolved_lat,
            longitude=resolved_lon,
            supporting_env_info=resolved_env,
            model_version=str(resolved_model),
            data_source=str(resolved_source),
            status="new",
            escalated_from=cooldown_check.get("escalated_from"),
            created_at=eval_now,
        )

        persisted = get_alert_by_id(alert_id) or {}
        final_lat = persisted.get("latitude", resolved_lat)
        final_lon = persisted.get("longitude", resolved_lon)
        final_loc_name = persisted.get("location_name") or location_name

        alert = {
            "id": alert_id,
            "location_id": location_id,
            "location_name": final_loc_name,
            "latitude": float(final_lat) if final_lat is not None else None,
            "longitude": float(final_lon) if final_lon is not None else None,
            "risk_category": risk_category,
            "probability": round(prob_f, 4),
            "supporting_env_info": resolved_env,
            "model_version": str(resolved_model),
            "data_source": str(resolved_source),
            "status": "new",
            "escalated_from": cooldown_check.get("escalated_from"),
            "is_escalation": bool(cooldown_check.get("is_escalation", False)),
            "created_at": eval_now.isoformat(),
            "is_experimental": True,
            "prediction_id": prediction_id,
            "notice": EXPERIMENTAL_NOTICE,
        }

        alert["notification_results"] = self.dispatcher.dispatch(alert)

        logger.info(
            "Experimental alert created: ID=%d, location=%s, category=%s, prob=%.4f, escalation=%s",
            alert_id,
            location_name or location_id,
            risk_category,
            prob_f,
            alert["escalated_from"] or "none",
        )
        return alert

    # ── Lifecycle & Queries ───────────────────────────────────────────

    def get_active_alerts(
        self,
        limit: int = MAX_ACTIVE_ALERTS,
        risk_category: str | None = None,
        start_date: str | None = None,
        end_date: str | None = None,
    ) -> pd.DataFrame:
        """Retrieve active unacknowledged alerts (status='new')."""
        return get_alerts(
            include_acknowledged=False,
            include_resolved=False,
            status="new",
            risk_category=risk_category,
            start_date=start_date,
            end_date=end_date,
            limit=limit,
        )

    def get_acknowledged_alerts(
        self,
        limit: int = 100,
        risk_category: str | None = None,
        start_date: str | None = None,
        end_date: str | None = None,
    ) -> pd.DataFrame:
        """Retrieve acknowledged (not yet resolved) alerts."""
        return get_alerts(
            include_acknowledged=True,
            include_resolved=False,
            status="acknowledged",
            risk_category=risk_category,
            start_date=start_date,
            end_date=end_date,
            limit=limit,
        )

    def get_resolved_alerts(
        self,
        limit: int = 100,
        risk_category: str | None = None,
        start_date: str | None = None,
        end_date: str | None = None,
    ) -> pd.DataFrame:
        """Retrieve resolved alerts."""
        return get_alerts(
            include_acknowledged=True,
            include_resolved=True,
            status="resolved",
            risk_category=risk_category,
            start_date=start_date,
            end_date=end_date,
            limit=limit,
        )

    def get_high_priority_alerts(
        self,
        limit: int = 100,
        include_resolved: bool = False,
    ) -> pd.DataFrame:
        """Retrieve High and Very High alerts prioritized for operator review."""
        df = get_alerts(
            include_acknowledged=True,
            include_resolved=include_resolved,
            limit=limit,
        )
        if df.empty or "risk_category" not in df.columns:
            return df
        return df[df["risk_category"].isin(["High", "Very High"])].reset_index(drop=True)

    def get_all_alerts(
        self,
        limit: int = 200,
        status: str | None = None,
        risk_category: str | None = None,
        start_date: str | None = None,
        end_date: str | None = None,
        location_id: int | None = None,
    ) -> pd.DataFrame:
        """Retrieve complete alert history with optional filters."""
        return get_alerts(
            include_acknowledged=True,
            include_resolved=True,
            status=status,
            risk_category=risk_category,
            start_date=start_date,
            end_date=end_date,
            location_id=location_id,
            limit=limit,
        )

    def get_alert(self, alert_id: int) -> dict | None:
        """Retrieve single alert details by ID."""
        return get_alert_by_id(alert_id)

    def acknowledge(self, alert_id: int, note: str | None = None) -> bool:
        """Acknowledge an alert and log an audit record."""
        result = db_acknowledge(alert_id, note)
        if result:
            logger.info("Alert %d acknowledged.", alert_id)
        return result

    def resolve(self, alert_id: int, note: str | None = None) -> bool:
        """Resolve an alert and log an audit record."""
        result = db_resolve(alert_id, note)
        if result:
            logger.info("Alert %d resolved.", alert_id)
        return result

    def get_audit_log(self, alert_id: int | None = None, limit: int = 100) -> pd.DataFrame:
        """Return acknowledgement and resolution audit log."""
        return get_alert_audit_log(alert_id=alert_id, limit=limit)

    def get_notification_status(self) -> list[dict[str, Any]]:
        """Report readiness status of external notification channels."""
        return self.dispatcher.get_channel_status()

    def check_location(
        self,
        features: dict,
        location_id: int | None = None,
        location_name: str | None = None,
        latitude: float | None = None,
        longitude: float | None = None,
        data_source: str | None = None,
        trigger_category: str | None = None,
    ) -> dict:
        """Full pipeline: estimate risk -> evaluate alert -> return result."""
        from src.risk.risk_engine import get_risk_engine

        engine = get_risk_engine()
        risk_result = engine.estimate_risk(features=features, location_name=location_name)

        alert = self.evaluate_and_alert(
            risk_result=risk_result,
            location_id=location_id,
            location_name=location_name,
            latitude=latitude,
            longitude=longitude,
            supporting_env_info=features,
            model_version=get_setting("model", "active_model") or "best_model",
            data_source=data_source or "Interactive Risk Evaluation",
            trigger_category=trigger_category,
        )

        return {
            "risk_result": risk_result,
            "alert_generated": alert is not None,
            "alert": alert,
        }


# Module-level singleton
_manager: AlertManager | None = None


def get_alert_manager() -> AlertManager:
    """Return the module-level AlertManager singleton."""
    global _manager
    if _manager is None:
        _manager = AlertManager()
    return _manager
