"""
Alert management system for LandslideGuard.

Implements:
- Alert generation based on risk thresholds
- Cooldown enforcement to prevent repeated notifications
- Alert acknowledgement
- Audit log maintenance

IMPORTANT: Alerts generated by this system are EXPERIMENTAL.
They must not be communicated as official disaster warnings.
This system has not been validated by any geological or disaster
management authority.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

import pandas as pd

from src.database.models import (
    create_alert,
    get_alerts,
    acknowledge_alert as db_acknowledge,
    is_on_cooldown,
    save_prediction,
)
from src.risk.thresholds import get_thresholds
from src.utils.logging_config import get_logger
from src.utils.settings import get_setting

logger = get_logger(__name__)

ALERT_TRIGGER_CATEGORY = get_setting("alerts", "trigger_category") or "High"
COOLDOWN_MINUTES = int(get_setting("alerts", "cooldown_minutes") or 120)
MAX_ACTIVE_ALERTS = int(get_setting("alerts", "max_active_alerts") or 50)


class AlertManager:
    """Manages the lifecycle of experimental risk alerts.

    All alerts carry an 'is_experimental' flag and include clear
    documentation that they are not operational warnings.
    """

    def __init__(self) -> None:
        self._thresholds = get_thresholds()

    def evaluate_and_alert(
        self,
        risk_result: dict,
        location_id: int | None = None,
        location_name: str | None = None,
    ) -> dict | None:
        """Evaluate a risk result and create an alert if warranted.

        Args:
            risk_result: Output from RiskEngine.estimate_risk().
            location_id: Optional database location ID.
            location_name: Optional human-readable location name.

        Returns:
            Alert record dict if created, or None.
        """
        probability = risk_result.get("probability")
        risk_category = risk_result.get("risk_category", "Unknown")

        if probability is None:
            logger.debug("No probability in risk result; skipping alert evaluation.")
            return None

        # Check alert threshold
        should_alert = self._thresholds.exceeds_alert_threshold(
            probability, ALERT_TRIGGER_CATEGORY
        )

        if not should_alert:
            logger.debug(
                "Risk category '%s' below alert threshold '%s'. No alert.",
                risk_category, ALERT_TRIGGER_CATEGORY,
            )
            return None

        # Check cooldown
        if is_on_cooldown(location_id, risk_category):
            logger.info(
                "Alert suppressed for location %s (%s): still within cooldown period.",
                location_name or location_id, risk_category,
            )
            return None

        # Save prediction to database
        prediction_id = save_prediction(
            probability=probability,
            risk_category=risk_category,
            model_name=risk_result.get("method", "unknown"),
            method=risk_result.get("method", "unknown"),
            input_features=risk_result.get("features_used", {}),
            warnings=risk_result.get("warnings", []),
            location_id=location_id,
            is_experimental=True,
        )

        # Create alert
        alert_id = create_alert(
            risk_category=risk_category,
            probability=probability,
            location_id=location_id,
            prediction_id=prediction_id,
            cooldown_minutes=COOLDOWN_MINUTES,
        )

        alert = {
            "id": alert_id,
            "location_id": location_id,
            "location_name": location_name,
            "risk_category": risk_category,
            "probability": probability,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "is_experimental": True,
            "prediction_id": prediction_id,
            "notice": (
                "⚠️ EXPERIMENTAL ALERT — This is a research prototype alert. "
                "It has NOT been validated and must NOT be used for evacuation "
                "or emergency management decisions."
            ),
        }

        logger.info(
            "Experimental alert created: ID=%d, location=%s, category=%s, prob=%.4f",
            alert_id, location_name or location_id, risk_category, probability,
        )
        return alert

    def get_active_alerts(self) -> pd.DataFrame:
        """Retrieve active (unacknowledged) alerts.

        Returns:
            DataFrame of active alerts.
        """
        return get_alerts(include_acknowledged=False, limit=MAX_ACTIVE_ALERTS)

    def get_all_alerts(self, limit: int = 200) -> pd.DataFrame:
        """Retrieve all alerts including acknowledged ones.

        Returns:
            DataFrame of all alerts.
        """
        return get_alerts(include_acknowledged=True, limit=limit)

    def acknowledge(self, alert_id: int, note: str | None = None) -> bool:
        """Acknowledge an alert.

        Args:
            alert_id: Alert record ID.
            note: Optional acknowledgement note.

        Returns:
            True if acknowledged successfully, False if alert was not found.
        """
        result = db_acknowledge(alert_id, note)
        if result:
            logger.info("Alert %d acknowledged.", alert_id)
        return result

    def check_location(
        self,
        features: dict,
        location_id: int | None = None,
        location_name: str | None = None,
    ) -> dict:
        """Full pipeline: estimate risk → evaluate alert → return result.

        Args:
            features: Environmental and terrain feature dict.
            location_id: Optional database location ID.
            location_name: Optional location name.

        Returns:
            Dict with risk estimate and alert (if generated).
        """
        from src.risk.risk_engine import get_risk_engine

        engine = get_risk_engine()
        risk_result = engine.estimate_risk(features=features, location_name=location_name)

        alert = self.evaluate_and_alert(
            risk_result=risk_result,
            location_id=location_id,
            location_name=location_name,
        )

        return {
            "risk_result": risk_result,
            "alert_generated": alert is not None,
            "alert": alert,
        }


# Module-level singleton
_manager: AlertManager | None = None


def get_alert_manager() -> AlertManager:
    """Return the module-level AlertManager singleton."""
    global _manager
    if _manager is None:
        _manager = AlertManager()
    return _manager
